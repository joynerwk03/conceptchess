"""Emit core/eval_data.h from the Python eval — weights and PST tables.

Generating the C constants from the single Python source guarantees the
compiled eval uses the same numbers as the authoritative Python eval, so the
two can't silently drift. Re-run whenever weights or tables change.

Run: .venv/bin/python core/gen_eval_data.py
"""

from pathlib import Path

from engine.weights import W, W_EG
from engine.concepts import piece_placement as pp
from engine.concepts.pawn_structure import PASSED_BONUS

OUT = Path(__file__).parent / "eval_data.h"


# Every number crosses into C at full double precision. %g would round to six
# significant digits, which was invisible while the weights were round numbers
# and became a 9e-5 disagreement the moment the tuner emitted six *decimals*.
# The invariant this project rests on is that the C eval IS the Python eval, so
# the generator must not be the thing that makes them differ. .17g round-trips
# an IEEE double exactly.
NUM = ".17g"


def c_array(name, values, per_line=8):
    lines = [f"static const double {name}[{len(values)}] = {{"]
    for i in range(0, len(values), per_line):
        chunk = ", ".join(f"{v:{NUM}}" for v in values[i:i + per_line])
        lines.append("    " + chunk + ",")
    lines.append("};")
    return "\n".join(lines)


def main():
    parts = ["/* Auto-generated by core/gen_eval_data.py — do not edit. */",
             "#ifndef EVAL_DATA_H", "#define EVAL_DATA_H", ""]

    # PST tables (flat, indexed by square 0..63 from White's side)
    for name, tbl in [("PST_PAWN_MG", pp.PAWN_MG), ("PST_PAWN_EG", pp.PAWN_EG),
                      ("PST_KNIGHT_MG", pp.KNIGHT_MG), ("PST_KNIGHT_EG", pp.KNIGHT_EG),
                      ("PST_BISHOP_MG", pp.BISHOP_MG), ("PST_BISHOP_EG", pp.BISHOP_EG),
                      ("PST_ROOK_MG", pp.ROOK_MG), ("PST_ROOK_EG", pp.ROOK_EG),
                      ("PST_QUEEN_MG", pp.QUEEN_MG), ("PST_QUEEN_EG", pp.QUEEN_EG),
                      ("PST_KING_MG", pp.KING_MG), ("PST_KING_EG", pp.KING_EG)]:
        parts.append(c_array(name, tbl))
        parts.append("")

    from engine.concepts.king_attack import KD_MG, KD_EG
    parts.append(c_array("KD_MG", KD_MG))
    parts.append("")
    parts.append(c_array("KD_EG", KD_EG))
    parts.append("")
    parts.append("#define KD_MAX 128")
    parts.append("")
    from engine.concepts.threats import THREAT_MG, THREAT_EG, _KINDS, _ORDER
    parts.append(c_array("THR_MG",
        [THREAT_MG[k][pt] for k in _KINDS for pt in _ORDER], per_line=5))
    parts.append("")
    parts.append(c_array("THR_EG",
        [THREAT_EG[k][pt] for k in _KINDS for pt in _ORDER], per_line=5))
    parts.append("")
    parts.append(c_array("PASSED_BONUS", PASSED_BONUS))
    parts.append("")

    # Weights as #defines (identifier-safe names).
    #
    # Each one is emitted as a MIDDLEGAME/ENDGAME pair. Where the two are equal
    # -- which is every key until the tuner fills W_EG -- the TAP() macro in
    # core/ceval.c compares two compile-time constants, so the compiler folds it
    # to the plain middlegame value and the generated code is identical to what
    # it was before tapering existed. Introducing the machinery therefore costs
    # nothing at all, in speed or in behaviour.
    parts.append("/* weights from engine/weights.py, as (middlegame, endgame) pairs */")
    # mobility curves: one array per piece, indexed by safe-square count.
    # Emitted as arrays rather than relying on the per-key defines, because the
    # C side indexes them with a runtime count.
    for _pc, _mx in (("knight", 8), ("bishop", 13), ("rook", 14), ("queen", 27)):
        parts.append(c_array(f"MOB_{_pc.upper()}_MG",
                           [W[f"mob.{_pc}.{i}"] for i in range(_mx + 1)]))
        parts.append(c_array(f"MOB_{_pc.upper()}_EG",
                           [W_EG.get(f"mob.{_pc}.{i}", W[f"mob.{_pc}.{i}"])
                            for i in range(_mx + 1)]))

    for key, val in W.items():
        macro = "W_" + key.replace(".", "_").upper()
        eg = W_EG.get(key, val)
        parts.append(f"#define {macro}_MG ({float(val):{NUM}})")
        parts.append(f"#define {macro}_EG ({float(eg):{NUM}})")
        # Back-compat alias so untapered call sites (material, which feeds SEE)
        # keep working unchanged.
        parts.append(f"#define {macro} ({float(val):{NUM}})")
    parts.append("")
    parts.append("#endif")
    OUT.write_text("\n".join(parts) + "\n")
    print(f"wrote {OUT} ({len(W)} weights, 12 PST tables)")


if __name__ == "__main__":
    main()
